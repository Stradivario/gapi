import { writeFileSync } from 'fs';
import { dump } from 'js-yaml';
import { forkJoin, lastValueFrom, of, throwError } from 'rxjs';
import { catchError, map, switchMap, tap } from 'rxjs/operators';

import { parseProjectId } from '~/helpers';
import { GraphqlClienAPI, ProjectDomain } from '~/services/gql-client';
import { Logger } from '~/services/log';

import { Loose } from './drift';

const SCALE_KEYS = [
  'executorType',
  'minScale',
  'maxScale',
  'targetCpu',
  'minCpu',
  'maxCpu',
  'minMemory',
  'maxMemory',
  'concurrency',
  'functionTimeout',
  'specializationTimeout',
  'idleTimeout',
];
const ENV_KEYS = [
  'name',
  'image',
  'builder',
  'poolSize',
  'maxPods',
  'builderPoolSize',
  'builderMaxParallelBuilds',
  'builderIdleTimeout',
  'minCpu',
  'maxCpu',
  'minMemory',
  'maxMemory',
  'region',
];

const names = (list: unknown) =>
  ((list as Loose[]) ?? [])
    .map((x) => (typeof x === 'string' ? x : x?.name))
    .filter(Boolean);

/** Drop empty values so the file only says what was chosen. */
const compact = (o: Loose): Loose =>
  Object.fromEntries(
    Object.entries(o).filter(
      ([, v]) =>
        v !== undefined &&
        v !== null &&
        v !== '' &&
        !(Array.isArray(v) && !v.length),
    ),
  );

const pick = (o: Loose | undefined, keys: string[]) =>
  compact(Object.fromEntries(keys.map((k) => [k, o?.[k]])));

/** The domains entry that serves `lambda` (whole host or a path rule). */
export const domainsOf = (
  lambdaId: string,
  lambdaName: string,
  domains: ProjectDomain[],
) =>
  domains.flatMap((d): Loose[] => {
    const key = d.platform
      ? { name: d.hostname.split('.')[0] }
      : { host: d.hostname };
    if (d.routeMode === 'prefix' && d.lambdaId === lambdaId)
      return [{ ...key }];
    const rules = (d.paths ?? []).filter((p) => p.lambdaId === lambdaId);
    if (!rules.length) return [];
    return [
      {
        ...key,
        paths: Object.fromEntries(rules.map((p) => [p.prefix, lambdaName])),
      },
    ];
  });

/** A lambforge.yaml for one running lambda - pure. Secret / config NAMES only. */
export function toYaml(
  lambda: Loose,
  env: Loose | undefined,
  trigger: Loose | undefined,
  domains: Loose[],
) {
  const spec: Loose = compact({
    function: compact({
      name: lambda.name,
      route: lambda.route,
      file: 'index.ts',
      env: lambda.env,
      method: lambda.method,
      params: lambda.params,
      network: lambda.network,
      secrets: names(lambda.secrets),
      configs: names(lambda.configs),
      envSecrets: names(lambda.envSecrets),
      federation: lambda.federation || undefined,
      subgraphs: lambda.subgraphs,
      mcp: lambda.mcp || undefined,
      scaleOptions: Object.keys(pick(lambda.scaleOptions, SCALE_KEYS)).length
        ? pick(lambda.scaleOptions, SCALE_KEYS)
        : undefined,
    }),
    environment: env ? pick(env, ENV_KEYS) : undefined,
    triggers: trigger
      ? {
          time: {
            triggerName: trigger.triggerName ?? trigger.name,
            cron: trigger.cron,
          },
        }
      : undefined,
    domains: domains.length ? domains : undefined,
  });
  return (
    '# yaml-language-server: $schema=https://lambforge.com/schemas/lambforge.json\n' +
    `# generated by gcli export from the running lambda "${lambda.name}" - review before committing\n` +
    dump(spec, { lineWidth: 100, noRefs: true })
  );
}

/** gcli export <lambda> [-o file] - write a lambforge.yaml from what runs. */
export default (name: string, cmd: { project?: string; output?: string }) =>
  lastValueFrom(
    parseProjectId(cmd.project).pipe(
      switchMap((projectId) =>
        forkJoin({
          lambdas: GraphqlClienAPI.listLambdasForPlan(projectId),
          environments: GraphqlClienAPI.listEnvironments(projectId).pipe(
            map((e) => (e ?? []) as Loose[]),
          ),
          triggers: GraphqlClienAPI.listProjectTimeTriggers(projectId).pipe(
            map((t) => (t ?? []) as Loose[]),
            catchError(() => of([] as Loose[])),
          ),
          domains: GraphqlClienAPI.listProjectDomains(projectId).pipe(
            catchError(() => of([] as ProjectDomain[])),
          ),
        }),
      ),
      switchMap(({ lambdas, environments, triggers, domains }) => {
        const lambda = lambdas.find((l) => l.name === name);
        if (!lambda)
          return throwError(
            () => new Error(`No lambda "${name}" in the project`),
          );
        const env =
          environments.find(
            (e) =>
              e.name === lambda.env &&
              (e.clusterId ?? null) === (lambda.clusterId ?? null),
          ) ?? environments.find((e) => e.name === lambda.env);
        const trigger = triggers.find((t) => t.lambdaId === lambda.id);
        return of(
          toYaml(
            lambda,
            env,
            trigger,
            domainsOf(lambda.id, lambda.name, domains),
          ),
        );
      }),
      tap((yaml) => {
        if (cmd.output) {
          writeFileSync(cmd.output, yaml);
          Logger.info(`Wrote ${cmd.output}`);
        } else {
          process.stdout.write(yaml);
        }
      }),
    ),
  );
